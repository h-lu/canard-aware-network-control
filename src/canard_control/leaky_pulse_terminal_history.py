"""Exact terminal-history theorem for the finite leaky-FHN pulse.

The physical pulse is applied to the voltage equation on ``0 <= t <= 1``
from the quiet equilibrium history.  Both declared delays exceed one, so
every delayed slot seen during the pulse is the equilibrium.  The terminal
history at ``t=1`` is therefore generated by a smooth two-dimensional
parameter ODE, although it is an element of the RFDE phase space
``C([-tau_1,0], R^2)``.

This module records the exact reduction and a sign theorem for the true
stimulus variation.  It proves that the terminal-history curve is an
oriented C1 embedding.  It does *not* construct the inner periodic orbit's
stable manifold, pair its defining covector with the terminal-history
tangent, prove a threshold, or route either side to an attractor.
"""

